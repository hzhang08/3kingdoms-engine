#!/usr/bin/env python3
"""Verify the exact original slot used by the Electron screenshot; emit C++ layout.

This is deliberately hash-gated and read-only, not a general .e5s importer.
Unknown bytes are retained in the evidence fixture and never assigned semantics.
"""
import argparse, hashlib, json, struct
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def header(f):
    rows = ',\n'.join(' {' + ','.join(str(u[k]) for k in ['id','slot','side','x','y','direction','status']) + '}' for u in f['units'])
    fires = ','.join('{'+str(p['x'])+','+str(p['y'])+'}' for p in f['fires'])
    return ('#pragma once\n// Generated by tools/prototype_layout.py; source/evidence: tests/fixtures/prototype-electron-layout.json.\n'
            '// Exact captured slot layout only; prototype statistics and combat remain simplified.\n'
            'namespace caocao {\nstruct PrototypePlacement {int id,slot,side,x,y,direction,status;};\n'
            'inline constexpr PrototypePlacement electron_layout[]{\n'+rows+'\n};\n'
            'inline constexpr int electron_fires[][2]{'+fires+'};\n}\n')

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=Path('/Users/henryzhang/Downloads/sgzccz/Sv00s.e5s'))
    p.add_argument('--write-header', action='store_true')
    a = p.parse_args(); f = json.loads((ROOT/'tests/fixtures/prototype-electron-layout.json').read_text())
    raw = a.source.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == f['source_sha256'], 'unsupported slot hash'
    rows = [raw[0x515+n*26:0x515+(n+1)*26] for n in range(115)]
    assert all(r[6] == n for n,r in enumerate(rows)), 'slot index mismatch'
    visible = [r for r in rows if r[14] == 2]
    assert len(visible) == len(f['units']) == 22
    for r,u in zip(visible,f['units']):
        assert r.hex() == u['raw']
        assert struct.unpack_from('<HHH',r) == (u['id'],u['hp'],u['mp'])
        assert [r[n] for n in [6,7,8,9,17,24,15]] == [u[k] for k in ['slot','side','x','y','direction','status','flags']]
    fires = [raw[o:o+5] for o in range(0x33,0x515,5) if raw[o:o+5] != bytes([255])*5]
    assert len(fires) == len(f['fires']) == 27
    for r,u in zip(fires,f['fires']): assert list(r) == [u['x'],u['y'],26,u['previous_terrain'],0]
    dest = ROOT/'include/caocao/prototype_layout.hpp'
    if a.write_header: dest.write_text(header(f))
    else: assert dest.read_text() == header(f), 'generated layout header is stale'
    print('Verified exact-slot bytes: 22 units, 27 fires; source unchanged.')
