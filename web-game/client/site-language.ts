export function readLanguage(storage: Pick<Storage, 'getItem'>): Language {
 try { return storage.getItem(LANGUAGE_KEY) === 'en' ? 'en' : 'zh'; } catch { return 'zh'; }
}
export function saveLanguage(storage: Pick<Storage, 'setItem'>, language: Language) {
 try { storage.setItem(LANGUAGE_KEY, language); } catch { /* Keep the in-memory preference. */ }
}
export function siteText(source: string, language: Language, values: Record<string, string | number> = {}): string {
 const text = language === 'en' ? SITE_EN[source] ?? source : source;
 return text.replace(/\{(\w+)\}/g, (token, key) => Object.hasOwn(values, key) ? String(values[key]) : token);
}
export function languageLocale(language: Language) { return language === 'en' ? 'en-US' : 'zh-CN'; }
